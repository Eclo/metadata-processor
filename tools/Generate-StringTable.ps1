[CmdletBinding()]
param(
    [string]$InterpreterRoot,
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$manifest = Get-Content (Join-Path $root 'assets\compact-string-table.json') -Raw | ConvertFrom-Json
[string[]]$strings = $manifest.strings
[string[]]$ordered = $strings.Clone()
[Array]::Sort($ordered, [StringComparer]::Ordinal)
if ($manifest.version -ne 2 -or $manifest.lastId -ne 65534 -or
    $strings.Length -eq 0 -or ($strings -join "`0") -cne ($ordered -join "`0")) {
    throw 'Invalid compact string table contract or ordering.'
}
$utf8 = New-Object Text.UTF8Encoding($false)
$frozenVersion2Sha256 = '67cb81422fbcc6f5050d41afae2e44c9f939c9534bc6449fe9c6a858ada7c643'
$contract = "$($manifest.version)`n$($manifest.lastId)`n" + ($strings -join "`n") + "`n"
$sha256 = [Security.Cryptography.SHA256]::Create()
try {
    $digest = [BitConverter]::ToString($sha256.ComputeHash($utf8.GetBytes($contract))).Replace('-', '').ToLowerInvariant()
} finally {
    $sha256.Dispose()
}
if (!$manifest.frozen -or $manifest.catalogSha256 -cne $frozenVersion2Sha256 -or $digest -cne $frozenVersion2Sha256) {
    throw 'String-table contract 2 is frozen. Changed entries or IDs require a new contract version.'
}
$ids = New-Object 'System.Collections.Generic.Dictionary[string,int]' ([StringComparer]::Ordinal)
$roots = New-Object 'System.Collections.Generic.List[string]'
$offsets = New-Object 'System.Collections.Generic.List[int]'
$data = New-Object 'System.Collections.Generic.List[byte]'
$packingOrder = $strings | Sort-Object @{ Expression = { -$utf8.GetByteCount($_) } },
    @{ Expression = { [Array]::IndexOf($ordered, $_) } }
foreach ($text in $packingOrder) {
    if ($text.Length -eq 0 -or $text -match '[^\x20-\x7E]' -or $text.Contains('"') -or $text.Contains('\')) {
        throw "Unsupported catalog entry '$text'."
    }
    if ($ids.ContainsKey($text)) { throw "Duplicate catalog entry '$text'." }
    $offset = -1
    for ($i = 0; $i -lt $roots.Count; $i++) {
        if ($roots[$i].EndsWith($text, [StringComparison]::Ordinal)) {
            $offset = $offsets[$i] + $utf8.GetByteCount($roots[$i]) - $utf8.GetByteCount($text)
            break
        }
    }
    if ($offset -lt 0) {
        $offset = $data.Count
        $roots.Add($text)
        $offsets.Add($offset)
        $data.AddRange($utf8.GetBytes($text))
        $data.Add(0)
    }
    $ids.Add($text, $offset)
}
if ($data.Count -gt 65535 -or $strings.Length -gt 65534) { throw 'Catalog overflow.' }
$cs = @(
    '// Licensed to the .NET Foundation under one or more agreements.'
    '// The .NET Foundation licenses this file to you under the MIT license.'
    ''
    '// Generated by tools\Generate-StringTable.ps1; contract entries and IDs are frozen.'
    "// Frozen contract SHA-256: $digest"
    'using System;'
    'using System.Collections.Generic;'
    'using System.Linq;'
    ''
    'namespace nanoFramework.Tools.MetadataProcessor'
    '{'
    '    internal static class nanoStringsConstants'
    '    {'
    "        internal const ushort Version = $($manifest.version);"
    "        internal const ushort LastId = $($manifest.lastId);"
    "        internal const ushort Count = $($strings.Length);"
    '        internal const ushort FirstId = LastId - Count + 1;'
    ''
    '        private static readonly string[] s_strings ='
    '        {'
)
$cs += $strings | ForEach-Object { '            "' + $_ + '",' }
$cs += @(
    '        };'
    ''
    '        private static readonly IDictionary<string, ushort> s_ids = s_strings'
    '            .Select((value, index) => new { value, id = (ushort)(LastId - index) })'
    '            .ToDictionary(item => item.value, item => item.id, StringComparer.Ordinal);'
    ''
    '        internal static bool TryGetStringIndex(string value, out ushort index)'
    '        {'
    '            return s_ids.TryGetValue(value, out index);'
    '        }'
    ''
    '        internal static string TryGetString(ushort index)'
    '        {'
    '            return index >= FirstId && index <= LastId ? s_strings[LastId - index] : null;'
    '        }'
    '    }'
    '}'
)
$cpp = @(
    '// Copyright (c) .NET Foundation and Contributors'
    '// See LICENSE file in the project root for full license information.'
    ''
    '// Generated by metadata-processor tools\Generate-StringTable.ps1.'
    "// Frozen contract SHA-256: $digest"
    '#include <stddef.h>'
    '#include <nanoCLR_Types.h>'
    ''
    "static_assert(c_CLR_StringTable_Version == $($manifest.version), `"String table contract mismatch`");"
    "const size_t c_CLR_StringTable_Size = $($strings.Length);"
    "const CLR_STRING c_CLR_StringTable_LastId = $($manifest.lastId);"
    ''
    'const CLR_STRING c_CLR_StringTable_Lookup[] ='
    '{'
)
$cpp += $strings | ForEach-Object { '    ' + $ids[$_] + ',' }
$cpp += @('};', '', 'const char c_CLR_StringTable_Data[] =')
$cpp += $roots | ForEach-Object { '    "' + $_ + '\0"' }
$cpp += ';'

function Write-GeneratedFile([string]$Path, [string[]]$Lines) {
    $content = ($Lines -join "`r`n") + "`r`n"
    if ($Check) {
        if (!(Test-Path -LiteralPath $Path) -or [IO.File]::ReadAllText($Path) -cne $content) {
            throw "Generated file is out of date: $Path"
        }
    } else {
        [IO.File]::WriteAllText($Path, $content, (New-Object Text.UTF8Encoding($true)))
    }
}

Write-GeneratedFile (Join-Path $root 'MetadataProcessor.Shared\Utility\nanoStringsConstants.cs') $cs
if ($InterpreterRoot) {
    Write-GeneratedFile (Join-Path $InterpreterRoot 'src\CLR\Core\StringTableData.cpp') $cpp
}
Write-Host "$($strings.Length) entries; $($data.Count) string bytes + $($strings.Length * 2) lookup bytes."
